import { sigunguBySido } from "../../src/data/regions.js";

/**
 * 크론이 미리 데워 둘 지역.
 *
 * **왜 미리 데우나.** 응답 캐시는 하루 안에 받은 값이면 즉시 내주고
 * 갱신은 뒤에서 한다(`responseCache.ts`의 갱신 창). 그 창을 살려 두려면
 * 지역마다 **하루에 한 번은** 누군가 조회해야 하는데, 사람 발길이 뜸한
 * 지역은 그러지 못한다 — 그런 지역의 첫 방문자가 국토부 조회를 온전히
 * 기다린다(실측 7.2초). 크론이 대신 그 한 번을 채운다.
 *
 * 덤으로 주소→좌표 캐시(`geocodeCache`, 만료 없음)가 채워진다. 그쪽은
 * 한 번 데워지면 영구적이라, 첫 실행 이후로는 네이버 지오코딩 비용이
 * 거의 들지 않는다.
 *
 * ── 범위: 서울 자치구 + 6대 광역시 자치구 ─────────────────────────
 *
 * 사용자가 고른 범위다. 어디가 실제로 인기 있는지 알려 줄 접속 통계가
 * 아직 없어, **아파트 거래가 꾸준한 대도시 자치구**라는 대리 기준을
 * 썼다. 정적 데이터(`data/complexes.json`)는 세 지역만 덮고 있어
 * 순위를 매기는 데 쓸 수 없었다.
 *
 * 군·시는 뺀다(광역시의 군, 경기도의 시 등) — 늘리는 만큼 국토부
 * 일일 호출 한도를 먹는다. 지역 하나가 12개월치를 부르므로 12~36회다.
 *
 * ⚠ **광주는 이 데이터에서 전남과 통합돼 있다**(`전남광주통합특별시`).
 * 그래서 시도 이름만으로 고르면 광주 5개 자치구가 통째로 빠진다 —
 * 실제로 처음 짤 때 빠뜨렸고 아래 검사가 잡았다. 그 시도에서는
 * 자치구(`…구`)만 골라 시·군(목포시·담양군 등)은 남긴다.
 *
 * ⚠ **이 목록을 늘릴 때는 한도를 먼저 계산하라.** 전국 256곳으로
 * 넓히면 한 바퀴에 3,000~9,000회로, 개발계정 일일 한도(보통 1만 회)를
 * 거의 다 쓰거나 넘겨 **정작 사용자 조회가 막힌다.**
 */
const GU_ONLY_SIDO = [
  "부산광역시",
  "대구광역시",
  "인천광역시",
  "대전광역시",
  "울산광역시",
  // 광주 5개 자치구가 여기 들어 있다(위 ⚠ 참고).
  "전남광주통합특별시",
] as const;

export const WARM_REGION_CODES: readonly string[] = [
  ...sigunguBySido("서울특별시").map((r) => r.regionCode),
  ...GU_ONLY_SIDO.flatMap((sido) =>
    sigunguBySido(sido)
      // 자치구만 — 군(달성군·울주군·강화군…)과 시(목포시·여수시…)는 뺀다.
      .filter((r) => r.sigunguName.endsWith("구"))
      .map((r) => r.regionCode),
  ),
];
