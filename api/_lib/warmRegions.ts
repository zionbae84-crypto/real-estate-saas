import { sigunguBySido } from "../../src/data/regions.js";

/**
 * 크론이 미리 데워 둘 지역.
 *
 * **왜 미리 데우나.** 응답 캐시는 하루 안에 받은 값이면 즉시 내주고
 * 갱신은 뒤에서 한다(`responseCache.ts`의 갱신 창). 그 창을 살려 두려면
 * 지역마다 **하루에 한 번은** 누군가 조회해야 하는데, 사람 발길이 뜸한
 * 지역은 그러지 못한다 — 그런 지역의 첫 방문자가 국토부 조회를 온전히
 * 기다린다(실측 7.2초). 크론이 대신 그 한 번을 채운다.
 *
 * 덤으로 주소→좌표 캐시(`geocodeCache`, 만료 없음)가 채워진다. 그쪽은
 * 한 번 데워지면 영구적이라, 첫 실행 이후로는 네이버 지오코딩 비용이
 * 거의 들지 않는다.
 *
 * ── 범위: 서울 자치구 25곳 (사용자 결정) ────────────────────────
 *
 * 처음에는 광역시 자치구까지 70곳이었는데, **국토부가 막아 한 번에
 * 10곳 안팎밖에 못 데웠다**(실측: 40곳 시도 → 9곳 성공, 나머지 전부
 * `HTTP 429`). 하루 두 번으로는 70곳을 한 바퀴 도는 데 사흘 반이 걸려
 * 갱신 창(24시간)을 못 지킨다 — 대부분의 지역에서 데우기가 무의미해진다.
 *
 * 그래서 확실히 하루에 한 바퀴 도는 크기로 줄였다. **순위를 매기지
 * 않았다**: 어디를 사람이 많이 보는지 알려 줄 접속 통계가 없고,
 * 정적 데이터(`data/regions.json`)가 덮는 것은 강남·서초·송파 셋뿐이라
 * 25곳 중 다섯을 잘라낼 근거가 없다. 서울 전부가 임의 선택보다 낫다.
 *
 * ⚠ **이 목록을 늘릴 때는 한도를 먼저 계산하라.** 지역 하나가 12개월치를
 * 부르므로 12~36회이고, 위 실측대로 한 실행에 10곳 안팎에서 막힌다.
 * 늘린 만큼 한 바퀴가 길어져, 어느 순간 갱신 창을 넘기면 데우기가
 * 하는 일이 없어진다.
 *
 * ⚠ **광역시를 다시 넣는다면 광주를 조심하라.** 이 데이터에서 광주는
 * 전남과 통합돼 `전남광주통합특별시`로 들어 있어(29xxx 코드가 아예 없다)
 * 시도 이름만으로 고르면 5개 자치구가 통째로 빠진다 — 처음 짤 때 실제로
 * 빠뜨렸고 검사가 잡았다.
 */

export const WARM_REGION_CODES: readonly string[] = sigunguBySido("서울특별시").map(
  (r) => r.regionCode,
);
