/**
 * "안전하다"·"사도 된다"는 **주장**을 문장 단위로 잡아내는 탐지기.
 *
 * 이 제품의 방침은 "사지 말아야 할 때를 말해주는 것"이고, 어떤 경로로도
 * 안전을 보증하지 않는 것이 그 방침의 핵심이다. 여러 테스트가 각자
 * 이 판단을 하다 보니 같은 정규식이 네 벌로 복사돼 있었고, 그중 둘은
 * 이미 서로 달랐다 — 안전 주장을 놓치는 그물이 조용히 생기는 자리다.
 * 그래서 한 곳으로 모은다.
 *
 * **이 파일이 `src/`가 아니라 `scripts/`에 있는 이유:** 앱이 쓰지 않는
 * 검사용 도구이기 때문이다(`tone-guard`·`motion-guard`·`printCss`와 같은
 * 자리). `src/`에 두면 아무도 부르지 않는 프로덕션 코드가 된다.
 *
 * ## 두 갈래로 나눈 이유
 *
 * 처음에는 "안전을 뜻하는 말이 있고 부정어가 없는 문장"만 잡았다. 그
 * 부정어 예외는 꼭 필요하다 — 이 제품이 가장 하고 싶은 말인 "'안전하다'는
 * 뜻이 아니에요"까지 걸리면 안 되기 때문이다.
 *
 * 그런데 리뷰가 면책 문구를 `"안심하고 진행하세요."`로 바꿔도 탐지기가
 * 보지 못하는 것을 실행으로 확인했다. 어휘를 넓히면서 알게 된 것은,
 * **안심을 권하는 말은 부정어를 품은 채로 온다**는 것이다 — "걱정 없어요",
 * "염려 없어요"는 부정어("없어")가 있다는 이유로 예외에 걸려 통째로
 * 빠져나간다. 그래서 안심 권유는 부정어 예외를 적용받지 않는 별도
 * 갈래로 둔다.
 */

/**
 * 안전을 긍정으로 주장하는 표현.
 *
 * 이 갈래는 {@link NEGATION} 예외를 적용받는다 — 부정문이면 오히려
 * 지켜야 하는 문장이다.
 */
const SAFETY_CLAIM = /안전|사도 (돼|되)|사도 좋|괜찮|문제없|이상 없/;

/** 부정·경고가 함께 있으면 안전 주장이 아니다 */
const NEGATION = /아니|않|없어|말아|마세|아닌/;

/**
 * 안심을 권하는 표현.
 *
 * **부정어 예외를 적용하지 않는다.** "걱정 없어요"·"염려 없어요"는
 * 부정어를 품고도 안심시키는 말이라, 예외를 적용하면 정확히 이 제품이
 * 하면 안 되는 말만 골라 통과시키게 된다.
 */
const REASSURANCE = /안심|염려\s*(없|말|마)|걱정\s*(없|말|마)|믿고|믿어도|마음\s*놓/;

/** 한국어 문장 경계로 자른다. 종결어미(요·다)와 문장부호를 함께 본다 */
function sentencesOf(phrase: string): string[] {
  return phrase.split(/(?<=[.!?)]|요|다)\s+/);
}

/**
 * 이 문구 안에서 "안전하다"고 주장하는 문장들을 돌려준다. 없으면 빈 배열.
 */
export function safetyClaimsIn(phrase: string): string[] {
  return sentencesOf(phrase).filter(
    (sentence) =>
      REASSURANCE.test(sentence) ||
      (SAFETY_CLAIM.test(sentence) && !NEGATION.test(sentence)),
  );
}

/** {@link safetyClaimsIn}의 불리언 판. 한 문장이라도 걸리면 참 */
export function claimsSafety(phrase: string): boolean {
  return safetyClaimsIn(phrase).length > 0;
}

/**
 * 탐지기가 반드시 잡아야 하는 문장들.
 *
 * 여기 실린 것 중 리뷰가 실제로 심었던 문구는 "안심하고 진행하세요."다 —
 * 면책 문구를 그것으로 바꿨을 때 1051개 테스트가 전부 통과했다.
 */
export const MUST_BE_CAUGHT: readonly string[] = [
  "이 집은 안전해요",
  "사도 돼요",
  "안심하고 진행하세요.",
  "걱정 없어요",
  "염려 없어요",
  "믿고 진행하셔도 돼요",
  "마음 놓으셔도 돼요",
  "이 집은 괜찮아요",
];

/**
 * 탐지기가 **놓아주어야** 하는 문장들.
 *
 * 부정문은 오히려 이 제품이 지켜야 하는 말이다. 그물을 넓힐 때마다
 * 여기가 함께 지켜지는지 확인한다.
 */
export const MUST_BE_ALLOWED: readonly string[] = [
  "'안전하다'는 뜻이 아니에요",
  "다 지나가도 안전하다고 말하지 않아요",
  "안전한지는 이 문진이 판단할 수 없어요",
  "걱정되면 법무사에게 보여 주세요",
];
